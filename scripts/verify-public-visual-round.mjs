import { chromium, firefox } from 'playwright'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'

const out = path.resolve(process.env.PUBLIC_TEST_OUTPUT || '.audit/public-round-20260922')
await fs.mkdir(out, { recursive: true })
const base = process.env.PUBLIC_TEST_URL || 'http://127.0.0.1:3100'
const engine = process.argv.includes('--firefox') ? firefox : chromium
const report = { engine: engine.name(), base, checks: [], errors: [] }
const browser = await engine.launch()
const passed = (check, details) => { report.checks.push({ check, details }); console.log('PASS', check, JSON.stringify(details ?? '')) }
const readScroll = track => track.evaluate(el => el.scrollLeft)
const wait = (page, ms) => page.waitForTimeout(ms)
const dismissConsent = async page => {
  const close = page.getByRole('button', { name: 'Cerrar preferencias sin cambiar la elección' })
  if (await close.isVisible()) await close.click()
}

try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' })
  const page = await context.newPage()
  page.on('pageerror', error => report.errors.push(String(error)))
  await page.goto(base, { waitUntil: 'networkidle' })
  await dismissConsent(page)
  const cta = page.locator('.rd-hero-copy a')
  await cta.scrollIntoViewIfNeeded()
  const before = await cta.boundingBox()
  await cta.screenshot({ path: path.join(out, `${engine.name()}-hero-rest.png`) })
  await cta.hover()
  await wait(page, 150)
  const midway = await page.locator('.rd-cta-glass').evaluate(el => Number(getComputedStyle(el).opacity))
  const duration = await page.locator('.rd-cta-glass').evaluate(el => getComputedStyle(el).transitionDuration)
  assert.equal(duration, '0.65s', `progressive hover duration ${duration}`)
  await wait(page, 700)
  const hovered = await cta.boundingBox()
  assert.equal(hovered.width, before.width)
  assert.equal(hovered.height, before.height)
  assert.equal(await page.locator('.rd-cta-label').evaluate(el => getComputedStyle(el).color), 'rgb(255, 255, 255)')
  assert.equal(await cta.evaluate(el => getComputedStyle(el).boxShadow), 'none')
  await cta.screenshot({ path: path.join(out, `${engine.name()}-hero-glass.png`) })
  passed('Progressive inner glass, unchanged pill size and white label', { midway })

  const gallery = page.locator('.rd-art-gallery')
  const track = page.locator('#art-gallery-track')
  await gallery.scrollIntoViewIfNeeded()
  await page.waitForFunction(() => document.querySelector('#art-gallery-track')?.dataset.motionRail === 'true')
  await page.mouse.move(0, 0)
  await wait(page, 300)
  const start = await readScroll(track)
  await wait(page, 1500)
  const drift = await readScroll(track) - start
  assert(drift > 5 && drift < 45, `slow drift ${drift}`)
  const box = await track.boundingBox()
  await page.mouse.move(box.x + box.width - 4, box.y + 100)
  const edgeStart = await readScroll(track)
  // Continuous pointer events must not keep resetting animation time.
  for (let i = 0; i < 30; i++) {
    await page.mouse.move(box.x + box.width - 4 - i % 3, box.y + 100 + i % 4)
    await wait(page, 20)
  }
  const edgeDelta = await readScroll(track) - edgeStart
  assert(edgeDelta > 20, `right edge while moving pointer ${edgeDelta}`)
  await page.mouse.move(box.x + 4, box.y + 100)
  const leftStart = await readScroll(track)
  await wait(page, 700)
  assert(await readScroll(track) < leftStart - 20, 'left edge reverses direction')
  await page.mouse.move(box.x + box.width / 2, box.y + 100)
  await wait(page, 100)
  const center = await readScroll(track)
  await wait(page, 600)
  assert(Math.abs(await readScroll(track) - center) < 2, 'hovering middle pauses')
  passed('Desktop slow drift and both accelerated pointer edges', { drift, edgeDelta })

  const pause = page.locator('.rd-art-gallery__pause')
  await pause.click()
  await page.mouse.move(0, 0)
  const paused = await readScroll(track)
  await wait(page, 700)
  assert(Math.abs(await readScroll(track) - paused) < 2)
  await pause.click()
  await page.mouse.move(0, 0)
  await wait(page, 700)
  assert(await readScroll(track) > paused + 3, 'resume button restarts motion')
  passed('Explicit pause and resume')

  const slider = page.locator('.rd-art-gallery__position')
  const sliderBox = await slider.boundingBox()
  await page.mouse.move(sliderBox.x + 20, sliderBox.y + sliderBox.height / 2)
  await page.mouse.down()
  await page.mouse.move(sliderBox.x + sliderBox.width * .7, sliderBox.y + sliderBox.height / 2, { steps: 8 })
  await page.mouse.up()
  await wait(page, 100)
  assert(Number(await slider.inputValue()) > 400)
  await slider.focus()
  const sliderBeforeKey = Number(await slider.inputValue())
  await slider.press('ArrowLeft')
  assert(Number(await slider.inputValue()) < sliderBeforeKey)
  // Stay beyond the gesture hold so focus itself must pause motion.
  await wait(page, 5300)
  const keyboardStart = await readScroll(track)
  await wait(page, 500)
  assert(Math.abs(await readScroll(track) - keyboardStart) < 2)
  await slider.press('Tab')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  assert.equal(await page.evaluate(() => Boolean(document.activeElement?.closest('.rd-art-gallery'))), false)
  // Do not send pointer/resize/scroll helper events: focusout must restart it.
  const stillVisible = await track.boundingBox()
  assert(stillVisible.y + stillVisible.height > 100, 'gallery remains on screen after Tab')
  const afterFocus = await readScroll(track)
  await wait(page, 900)
  assert(await readScroll(track) > afterFocus + 4, 'motion resumes after keyboard leaves controls')
  passed('Slider drag, native keys and resume after footer focus leaves')

  const next = page.getByRole('button', { name: 'Ver proyectos siguientes', exact: true })
  await page.getByRole('button', { name: 'Ver proyectos anteriores', exact: true }).click()
  await wait(page, 700)
  const previousScroll = await readScroll(track)
  await next.click()
  await wait(page, 800)
  assert(await readScroll(track) > previousScroll + 40, 'arrows retain manual movement')
  const gaps = await page.evaluate(() => {
    const gallery = document.querySelector('.rd-art-gallery').getBoundingClientRect()
    const label = document.querySelector('#casos > .rd-label').getBoundingClientRect()
    const title = document.querySelector('#casos h2').getBoundingClientRect()
    return { galleryToLabel: label.top - gallery.bottom, labelToHeading: title.top - label.bottom }
  })
  assert(gaps.labelToHeading >= 0 && gaps.labelToHeading < 20, JSON.stringify(gaps))
  assert(gaps.galleryToLabel >= 60 && gaps.galleryToLabel <= 100, JSON.stringify(gaps))
  assert.equal(await slider.evaluate(el => getComputedStyle(el).getPropertyValue('--rail-thumb').trim()), '#f2e9ff')
  await gallery.screenshot({ path: path.join(out, `${engine.name()}-gallery-dark.png`) })
  await page.locator('#casos').scrollIntoViewIfNeeded()
  await page.locator('.rd-cases-intro').screenshot({ path: path.join(out, `${engine.name()}-cases-heading.png`) })
  const arrowRecipes = await page.locator('.rd-art-gallery__controls button:not(.rd-art-gallery__pause)').evaluateAll(buttons => buttons.map(el => ({ border: getComputedStyle(el).borderTopWidth, stroke: getComputedStyle(el.querySelector('svg')).strokeWidth })))
  assert(arrowRecipes.length >= 4)
  assert(arrowRecipes.every(recipe => parseFloat(recipe.border) === 2 && recipe.stroke === '2px'), JSON.stringify(arrowRecipes))
  passed('Shared arrows, compact gradient scrollbar and separated section hierarchy', { gaps, arrowRecipes })

  const research = page.locator('#investigacion')
  await research.scrollIntoViewIfNeeded()
  await page.locator('.rd-research-artifact canvas').waitFor({ state: 'visible' })
  await page.waitForFunction(() => document.querySelector('[data-research-motion]')?.dataset.researchMotion === 'running')
  await page.mouse.move(0, 0)
  await wait(page, 1800)
  const offsets = await page.locator('.rd-research-artifact-canvas').evaluate(el => ({ x: getComputedStyle(el).getPropertyValue('--artifact-offset-x').trim(), y: getComputedStyle(el).getPropertyValue('--artifact-offset-y').trim() }))
  assert.deepEqual(offsets, { x: '-12px', y: '-28px' })
  await research.screenshot({ path: path.join(out, `${engine.name()}-saturn-desktop.png`) })
  await page.locator('.rd-theme-btn:visible').click()
  await wait(page, 300)
  assert.equal(await slider.evaluate(el => getComputedStyle(el).getPropertyValue('--rail-thumb').trim()), '#252c3b')
  await gallery.scrollIntoViewIfNeeded()
  await gallery.screenshot({ path: path.join(out, `${engine.name()}-gallery-light.png`) })
  passed('Research render, desktop placement and light scrollbar palette', offsets)

  await page.emulateMedia({ reducedMotion: 'reduce' })
  await gallery.scrollIntoViewIfNeeded()
  await page.mouse.move(0, 0)
  await wait(page, 300)
  const reducedStart = await readScroll(track)
  await wait(page, 1000)
  assert(Math.abs(await readScroll(track) - reducedStart) < 2)
  assert.equal(await pause.isVisible(), false)
  await research.scrollIntoViewIfNeeded()
  assert.equal(await page.locator('[data-research-motion]').getAttribute('data-research-motion'), 'paused')
  passed('Reduced motion pauses both gallery and Saturn')
  await context.close()

  for (const width of [320, 390, 768]) {
    const mobile = await browser.newContext({ viewport: { width, height: 900 }, hasTouch: true, isMobile: engine === chromium, reducedMotion: 'no-preference' })
    const p = await mobile.newPage()
    p.on('pageerror', error => report.errors.push(String(error)))
    await p.goto(base, { waitUntil: 'networkidle' })
    await dismissConsent(p)
    const g = p.locator('.rd-art-gallery')
    const t = p.locator('#art-gallery-track')
    await g.scrollIntoViewIfNeeded()
    await p.waitForFunction(() => document.querySelector('#art-gallery-track')?.dataset.motionRail === 'true')
    const still = await readScroll(t)
    await wait(p, 700)
    assert.equal(await readScroll(t), still, `no mobile automatic movement ${width}`)
    const range = p.locator('.rd-art-gallery__position')
    const rangeBox = await range.boundingBox()
    await p.touchscreen.tap(rangeBox.x + rangeBox.width * .8, rangeBox.y + rangeBox.height / 2)
    await wait(p, 300)
    assert(await readScroll(t) > still + 20, `mobile touchscreen slider ${width}`)
    const controls = await p.locator('.rd-art-gallery__controls--motion').boundingBox()
    assert(controls.x >= 0 && controls.x + controls.width <= width + 1)
    const mobileGap = await p.evaluate(() => document.querySelector('#casos h2').getBoundingClientRect().top - document.querySelector('#casos > .rd-label').getBoundingClientRect().bottom)
    assert(mobileGap >= 0 && mobileGap < 20, `label gap ${width}: ${mobileGap}`)
    await g.screenshot({ path: path.join(out, `${engine.name()}-gallery-${width}.png`) })
    await p.locator('#investigacion').scrollIntoViewIfNeeded()
    await p.locator('.rd-research-artifact canvas').waitFor({ state: 'visible' })
    await wait(p, 800)
    await p.locator('#investigacion').screenshot({ path: path.join(out, `${engine.name()}-saturn-${width}.png`) })
    passed(`Touch layout ${width}px`, { controls, mobileGap })
    await mobile.close()
  }
  assert.deepEqual(report.errors, [], 'no page runtime errors')
  report.result = 'PASS'
} catch (error) {
  report.result = 'FAIL'
  report.failure = String(error.stack || error)
  console.error(report.failure)
  process.exitCode = 1
} finally {
  await fs.writeFile(path.join(out, `${engine.name()}-browser-results.json`), JSON.stringify(report, null, 2))
  await browser.close()
}
