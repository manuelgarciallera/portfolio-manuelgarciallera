import assert from 'node:assert/strict'
import {chromium,firefox} from 'playwright'
const browser=await (process.env.HERO_BROWSER==='firefox'?firefox:chromium).launch()
try{
 const base=process.env.HERO_TEST_URL||'http://127.0.0.1:3033'
 const page=await browser.newPage({viewport:{width:390,height:844}})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.addInitScript(()=>{localStorage.setItem('rd-theme','dark');Object.defineProperty(navigator,'doNotTrack',{get:()=> '1'})})
 await page.goto(`${base}/lab/orbes`,{waitUntil:'domcontentloaded'})
 assert.equal(await page.locator('iframe[title="Prueba de orbes"]').count(),1,'isolated lab page exists')
 assert.match(await page.locator('meta[name="robots"]').getAttribute('content'),/noindex/)
 const frame=page.frameLocator('iframe')
 const warm=frame.locator('.rd-dual-warm');await warm.waitFor({state:'attached',timeout:60000})
 assert.equal(await warm.evaluate(e=>Number(getComputedStyle(e).opacity)),0)
 await frame.locator('.rd-hero-canvas-stage').evaluate(e=>{const w=e.ownerDocument.defaultView;w.scrollTo(0,w.scrollY+e.getBoundingClientRect().top-250)})
 await page.waitForTimeout(1500)
 assert.ok(await warm.evaluate(e=>Number(getComputedStyle(e).opacity))>.95)
 await page.waitForFunction(()=>{const f=document.querySelector('iframe');return Number(f.contentDocument.querySelector('.rd-dual-warm')?.dataset.absorptions)>0},null,{timeout:20000})
 await page.screenshot({path:'.audit/mobile-dual-orb/published-lab.png'})
 await page.emulateMedia({reducedMotion:'reduce'});await page.waitForTimeout(400)
 const stopped=await warm.getAttribute('data-draws');await page.waitForTimeout(400);assert.equal(await warm.getAttribute('data-draws'),stopped)
 await page.emulateMedia({reducedMotion:'no-preference'})
 await frame.getByRole('button',{name:'Comparar: solo azul'}).click()
 assert.equal(await warm.isVisible(),false)
 await frame.getByRole('button',{name:'Comparar: dos orbes'}).click()
 await warm.evaluate(e=>{e.dispatchEvent(new Event('webglcontextlost',{cancelable:true}))})
 assert.equal(await warm.count(),0,'failed warm renderer cleans itself up')
 assert.equal(await frame.locator('.rd-hero-canvas-stage canvas').count(),1,'blue remains')
 await page.getByRole('link',{name:'Salir de la prueba y volver al portfolio original'}).click()
 await page.waitForURL(base+'/')
 assert.equal(await page.locator('iframe').count(),0,'exit unmounts the lab')
 assert.equal(await page.locator('.rd-dual-warm').count(),0,'normal homepage unchanged')
 assert.deepEqual(errors,[])
 console.log('PASS noindex lab, formation, compare, failure cleanup, blue retained, homepage isolated')
}finally{await browser.close()}
